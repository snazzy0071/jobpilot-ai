// Writes supabase/migrations/0107_test_prep_question_bank.sql from the bank in bank.mjs.
//   node scripts/test-prep-content/build-migration.mjs
// The migration is idempotent (packs upsert on (test type, slug); a question is only inserted if its pack has none at
// that display order), so re-running it against a database that already has the bank changes nothing.

import fs from "node:fs";
import { buildBank } from "./bank.mjs";

const { packs, questions, legacy } = buildBank();

const json = (value) => JSON.stringify(value);

const packRows = packs.map((p) => ({
  type_slug: p.typeSlug,
  slug: p.slug,
  name: p.name ?? null,
  description: p.description ?? null,
  sector_style: p.sectorStyle ?? null,
  time_limit_seconds: p.timeLimitSeconds,
  existing: p.existing === true,
}));

const questionRows = questions.map((q) => ({
  pack_slug: q.packSlug,
  type_slug: q.typeSlug,
  display_order: q.displayOrder,
  subtype: q.subtype,
  difficulty: q.difficulty,
  stimulus: q.stimulus,
  prompt: q.prompt,
  options: q.options,
  correct_answer: q.correctAnswer,
  explanation: q.explanation,
  exhibit: q.exhibit,
  option_figures: q.optionFigures,
}));

const legacyRows = legacy.map((l) => ({
  pack_slug: l.pack,
  display_order: l.order,
  subtype: l.subtype,
  difficulty: l.difficulty,
  stimulus: l.stimulus ?? null,
  prompt: l.prompt ?? null,
}));

const header = `-- Test Prep question bank: original practice content for all five formats (critical thinking in its five argument
-- formats, situational judgement, numerical, verbal and diagrammatic reasoning).
--
-- GENERATED by scripts/test-prep-content/build-migration.mjs from the sources in that folder — edit those (and re-run the
-- script) rather than this file. Everything is original: the numerical and diagrammatic questions are generated from
-- explicit rules so each answer is correct by construction and every distractor is a specific wrong method (verified by
-- src/lib/test-prep/content.test.ts); the passages, scenarios and statements were written for this product. Nothing is
-- copied from or adapted from any published aptitude test.
--
-- What it does:
--   1. Adds the new packs and gives every pack a real time limit (questions x seconds per question for its format).
--   2. Rewrites the fifteen original questions that referred to "the same passage as above" (meaningless once questions are
--      shuffled or drawn for the daily five) so each carries its own passage, and tags all fifteen with a subtype and difficulty.
--   3. Adds the new questions. Idempotent: a question is only inserted where its pack has none at that display order.

`;

const sql = `${header}
with bank as (
  select * from jsonb_to_recordset($packs$${json(packRows)}$packs$::jsonb)
    as b(type_slug text, slug text, name text, description text, sector_style text, time_limit_seconds integer, existing boolean)
)
insert into public.question_packs (test_type_id, slug, name, description, sector_style, time_limit_seconds)
select t.id, b.slug, b.name, b.description, b.sector_style, b.time_limit_seconds
from bank b
join public.test_types t on t.slug = b.type_slug
where not b.existing
on conflict (test_type_id, slug) do update
  set name = excluded.name, description = excluded.description, sector_style = excluded.sector_style, time_limit_seconds = excluded.time_limit_seconds;

update public.question_packs p
set time_limit_seconds = b.time_limit_seconds
from jsonb_to_recordset($packs2$${json(packRows.filter((p) => p.existing))}$packs2$::jsonb)
  as b(type_slug text, slug text, name text, description text, sector_style text, time_limit_seconds integer, existing boolean)
where p.slug = b.slug;

with legacy as (
  select * from jsonb_to_recordset($legacy$${json(legacyRows)}$legacy$::jsonb)
    as l(pack_slug text, display_order integer, subtype text, difficulty public.question_difficulty, stimulus text, prompt text)
)
update public.questions q
set subtype = l.subtype,
    difficulty = l.difficulty,
    stimulus = coalesce(l.stimulus, q.stimulus),
    prompt = coalesce(l.prompt, q.prompt)
from legacy l
join public.question_packs p on p.slug = l.pack_slug
where q.question_pack_id = p.id and q.display_order = l.display_order;

with bank as (
  select * from jsonb_to_recordset($questions$${json(questionRows)}$questions$::jsonb)
    as b(pack_slug text, type_slug text, display_order integer, subtype text, difficulty public.question_difficulty,
         stimulus text, prompt text, options jsonb, correct_answer text, explanation text, exhibit jsonb, option_figures jsonb)
)
insert into public.questions
  (question_pack_id, question_type, prompt, options, correct_answer, explanation, display_order, difficulty, subtype, stimulus, exhibit, option_figures)
select p.id, 'multiple_choice', b.prompt, b.options, b.correct_answer, b.explanation, b.display_order, b.difficulty, b.subtype, b.stimulus, b.exhibit, b.option_figures
from bank b
join public.test_types t on t.slug = b.type_slug
join public.question_packs p on p.slug = b.pack_slug and p.test_type_id = t.id
where not exists (
  select 1 from public.questions q where q.question_pack_id = p.id and q.display_order = b.display_order
);
`;

const out = new URL("../../supabase/migrations/0107_test_prep_question_bank.sql", import.meta.url);
fs.writeFileSync(out, sql);
console.log(`Wrote ${out.pathname.replace(/^\//, "")}: ${packs.length} packs, ${questions.length} new questions, ${legacy.length} legacy rows updated (${Math.round(sql.length / 1024)} KB).`);
