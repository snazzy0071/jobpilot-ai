// Generates supabase/migrations/0115_advice_hub_seed.sql from guides.mjs. Idempotent (upsert by slug), and it only ever inserts
// guides that don't exist yet — re-running the migration never overwrites an edit an admin has made in the meantime.
import fs from "node:fs";
import { guides } from "./guides.mjs";

const lit = (value) => `'${String(value).replaceAll("'", "''")}'`;
const daysAgo = (n) => new Date(Date.UTC(2026, 8, 25 - n, 9, 0, 0)).toISOString();

const rows = guides.map((guide, index) => {
  const published = daysAgo(28 - index * 3); // staggered, so "newest first" has an order
  const reviewed = published.slice(0, 10);
  return `insert into public.advice_guides (slug, title, summary, category, content, featured_rank, related_slugs, author_name, reviewed_on, published_at)
values (
  ${lit(guide.slug)}, ${lit(guide.title)}, ${lit(guide.summary)}, ${lit(guide.category)},
  $json$${JSON.stringify(guide.content)}$json$::jsonb,
  ${guide.featured_rank ?? "null"}, array[${guide.related.map(lit).join(", ")}]::text[], 'JobPilot AI editorial team', ${lit(reviewed)}, ${lit(published)}
)
on conflict (slug) do nothing;`;
});

const sql = `-- GENERATED by scripts/advice-content/build-migration.mjs from scripts/advice-content/guides.mjs — edit those, not this file.
-- Opening set of original evergreen guides, one per Advice Hub category. Uses "on conflict do nothing", so re-applying never
-- overwrites edits made in the admin.

${rows.join("\n\n")}
`;

fs.writeFileSync("supabase/migrations/0115_advice_hub_seed.sql", sql);
console.log(`wrote ${guides.length} guides`);
