import type { Metadata } from "next";
import { notFound } from "next/navigation";
import { siteConfig } from "@/config/site";
import { getQuickScanResultByToken } from "@/lib/quick-scan/results";

export const dynamic = "force-dynamic";

export async function generateMetadata(): Promise<Metadata> {
  return { title: "ATS scan report", robots: { index: false, follow: false } };
}

function scoreLabel(score: number): string {
  if (score >= 80) return "Strong match";
  if (score >= 50) return "Partial match";
  return "Weak match";
}

// Deliberately outside every route group — no nav/header/footer, exists
// purely for Puppeteer to capture as a PDF
// (src/lib/quick-scan/pdf-export.ts, src/app/api/quick-scan/[token]/pdf).
// Reachable by a human directly too, but it only ever shows the same
// reduced result the token's owner already saw — the token itself
// (unguessable, hashed at rest — see src/lib/quick-scan/results.ts) is
// the only access control, there's no account to check.
export default async function QuickScanPrintPage({ params }: { params: Promise<{ token: string }> }) {
  const { token } = await params;
  const result = await getQuickScanResultByToken(token);
  if (!result) notFound();

  const generatedOn = new Intl.DateTimeFormat("en-GB", { day: "numeric", month: "long", year: "numeric" }).format(
    new Date(),
  );

  return (
    <>
      <style>{`
        @page { size: A4; margin: 18mm 16mm; }
        html, body { background: #fff; margin: 0; color: #111827; font-family: Arial, Helvetica, sans-serif; }
        .report { max-width: 100%; }
        .report h1 { font-size: 22px; margin: 0 0 2px; }
        .report .meta { color: #6b7280; font-size: 11px; margin: 0 0 20px; }
        .report .score-row { display: flex; align-items: baseline; gap: 8px; margin-bottom: 4px; }
        .report .score { font-size: 40px; font-weight: 700; }
        .report .score-out-of { color: #6b7280; font-size: 13px; }
        .report .score-label { font-size: 13px; font-weight: 600; margin-bottom: 16px; }
        .report .summary { font-size: 13px; line-height: 1.6; margin-bottom: 20px; }
        .report section { margin-bottom: 18px; break-inside: avoid; }
        .report h2 { font-size: 13px; text-transform: uppercase; letter-spacing: 0.04em; color: #6b7280; margin: 0 0 8px; }
        .report .chips { display: flex; flex-wrap: wrap; gap: 6px; }
        .report .chip { border: 1px solid #d1d5db; border-radius: 999px; padding: 3px 10px; font-size: 12px; }
        .report .chip.matched { background: #ecfdf5; border-color: #a7f3d0; color: #047857; }
        .report .chip.missing { background: #fffbeb; border-color: #fde68a; color: #b45309; }
        .report ul { margin: 0; padding-left: 18px; font-size: 13px; line-height: 1.6; }
        .report .footer { margin-top: 24px; padding-top: 12px; border-top: 1px solid #e5e7eb; font-size: 10px; color: #9ca3af; }
      `}</style>
      <div className="report">
        <h1>{siteConfig.name} — ATS Scan Report</h1>
        <p className="meta">Generated {generatedOn}</p>

        <div className="score-row">
          <span className="score">{result.overallScore}</span>
          <span className="score-out-of">/ 100 match with this job description</span>
        </div>
        <p className="score-label">{scoreLabel(result.overallScore)}</p>
        <p className="summary">{result.summary}</p>

        {result.matchedKeywords.length > 0 && (
          <section>
            <h2>Top matched keywords ({result.matchedKeywords.length})</h2>
            <div className="chips">
              {result.matchedKeywords.map((keyword) => (
                <span key={keyword} className="chip matched">
                  {keyword}
                </span>
              ))}
            </div>
          </section>
        )}

        {result.missingKeywords.length > 0 && (
          <section>
            <h2>Top missing keywords ({result.missingKeywords.length})</h2>
            <div className="chips">
              {result.missingKeywords.map((keyword) => (
                <span key={keyword} className="chip missing">
                  {keyword}
                </span>
              ))}
            </div>
          </section>
        )}

        {result.topFixes.length > 0 && (
          <section>
            <h2>Top fixes</h2>
            <ul>
              {result.topFixes.map((fix) => (
                <li key={fix}>{fix}</li>
              ))}
            </ul>
          </section>
        )}

        <p className="footer">
          Generated by {siteConfig.name} ({siteConfig.domain}) — a reduced, no-account preview. Create a free account
          for the full score breakdown, complete keyword and fix list, and AI-suggested rewrites.
        </p>
      </div>
    </>
  );
}
